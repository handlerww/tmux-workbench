async page => {
  const base = 'http://127.0.0.1:17690';
  const repo = '/tmp/workbench-e2e/project/repos/other';
  const checks = [], errors = [];
  const assert = (ok, message) => { if (!ok) throw new Error(message); checks.push(message); };
  page.on('pageerror', error => errors.push(error.message));
  const sessions = (await (await page.request.get(base + '/api/sessions')).json()).sessions;
  const alpha = sessions.find(session => session.name === 'workbench-alpha');
  if (!alpha) throw new Error('Missing owned fixture');
  const status = async () => (await (await page.request.get(base + '/api/git?session=' + encodeURIComponent(alpha.id))).json());
  let current = await status();
  if (current.association.path) await page.request.put(base + '/api/git/association', { headers: { Origin: base }, data: { session: alpha.id, path: null, revision: current.association.revision } });
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto(base);
  await page.evaluate(async () => { for (const worker of await navigator.serviceWorker.getRegistrations()) await worker.unregister(); localStorage.clear(); });
  await page.reload();
  const card = page.locator('.session-card').filter({ hasText: alpha.name });
  await card.click();
  await page.locator('#right-git-tab').click();
  await page.waitForFunction(() => !document.querySelector('.git-repository-search').disabled);
  assert(await page.locator('.git-session-status.is-error').count() === 0, 'First opening unbound Git loads candidates without an empty-selection error');
  await page.locator(`.git-recommendation[data-repository-path="${repo}"]`).click();
  await page.locator('.git-change-folder[data-git-folder="src"]').waitFor();
  const tree = page.getByRole('tree', { name: 'Changed files' });
  assert(await tree.isVisible() && await page.locator('.git-panel .git-diff-section').count() === 0 && await page.locator('dialog.git-review-dialog').count() === 0, 'Changes is a dedicated file-tree column without sidebar diff or review modal');
  assert(await page.locator('.editor-tab').count() === 1, 'Repository association only populates the tree');
  assert(await page.locator('.git-change-row').count() === (await status()).changes.length, 'Each changed file appears once in the tree');
  const apiFolder = page.locator('[data-git-folder="src/api"]');
  const handler = page.locator('[data-change-path="src/api/handler.js"][role="treeitem"]');
  assert(await apiFolder.isVisible() && await handler.getAttribute('aria-level') === '3', 'Nested directories and file indentation are represented in the tree');
  await apiFolder.click();
  assert(await handler.count() === 0 && await apiFolder.getAttribute('aria-expanded') === 'false', 'Directory rows collapse their changed files');
  await page.getByRole('button', { name: 'Refresh Git status' }).click();
  await apiFolder.waitFor();
  assert(await apiFolder.getAttribute('aria-expanded') === 'false', 'Polling or refreshing preserves collapsed folders');
  await page.getByRole('searchbox', { name: 'Filter changed files' }).fill('API HANDLER');
  await handler.waitFor();
  assert(await page.locator('.git-change-row').count() === 1, 'Keyword search reveals matching files through collapsed directories');
  await handler.click();
  const diff = page.locator('.git-diff-tab');
  await page.waitForFunction(() => [...document.querySelectorAll('.git-diff-tab .view-lines')].some(node => node.textContent.replace(/\s/g, ' ').includes('tree diff fixture')));
  assert(await page.locator('.editor-tab.diff-tab').count() === 1 && await page.locator('.editor-tab').count() === 2, 'Selecting a changed file opens a main workspace diff tab beside its session');
  const firstPreview = await page.locator('.editor-tab.diff-tab').getAttribute('data-tab-id');
  assert(await diff.locator('textarea').evaluateAll(nodes => nodes.length > 0 && nodes.every(node => node.readOnly)), 'The main diff tab is read-only');
  assert(await diff.locator('.monaco-diff-editor').evaluate(node => node.getBoundingClientRect().height > 500), 'Monaco fills the main workspace reading area');
  await page.getByRole('searchbox', { name: 'Filter changed files' }).fill('');
  const unstaged = page.locator('[data-change-path="git-unstaged.txt"][role="treeitem"]');
  await unstaged.click();
  await page.waitForFunction(() => document.querySelector('.git-diff-tab-path')?.textContent === 'git-unstaged.txt');
  assert(await page.locator('.editor-tab.diff-tab').count() === 1 && await page.locator('.editor-tab.diff-tab').getAttribute('data-tab-id') !== firstPreview, 'Single-clicking another file reuses the diff preview');
  await unstaged.dblclick();
  assert(await page.locator('.editor-tab.diff-tab').getByRole('button', { name: 'Unpin diff tab', exact: true }).isVisible(), 'Double-clicking a tree file pins its diff tab');
  await page.locator('[data-change-path="git-staged.txt"][role="treeitem"]').click();
  await page.waitForFunction(() => document.querySelector('.git-diff-tab-path')?.textContent === 'git-staged.txt');
  assert(await page.locator('.editor-tab.diff-tab').count() === 2, 'Pinned diff stays open when another preview is selected');
  await unstaged.click();
  assert(await page.locator('.editor-tab.diff-tab').count() === 2, 'Reopening the same diff focuses its existing tab');
  await page.locator('.editor-tab.diff-tab').filter({ hasText: 'git-staged.txt' }).click();
  assert(await page.locator('[data-change-path="git-staged.txt"][role="treeitem"]').getAttribute('aria-selected') === 'true', 'Changing the active diff tab synchronizes tree selection');
  await page.locator('[data-change-path="git-both.txt"][data-change-kind="staged"]').click();
  await page.waitForFunction(() => document.querySelector('.git-diff-tab-title')?.textContent.includes('Staged'));
  assert(await tree.locator('[data-change-path="git-both.txt"]').count() === 2 && await page.locator('.git-diff-tab-title').textContent().then(text => text.includes('Staged')), 'A mixed file has one tree row with a separate index version action');
  await page.reload();
  await page.locator('.git-diff-tab').waitFor();
  await page.locator('#right-git-tab').click();
  await page.locator('.git-change-row').first().waitFor();
  assert(await page.locator('.editor-tab.diff-tab').count() === 2 && await page.locator('.git-diff-tab-title').textContent().then(text => text.includes('Staged')), 'Diff tab descriptors and preview state restore after reload');
  assert(await apiFolder.getAttribute('aria-expanded') === 'false', 'Tree folder collapse restores after reload');
  await page.locator('.editor-group.active [aria-label="Split right"]').click();
  await page.waitForFunction(() => document.querySelectorAll('.editor-group').length === 2);
  assert(await page.locator('.git-diff-tab').count() === 2 && await page.locator('.split-divider').count() === 1, 'Diff tabs use existing workspace splits');
  await page.screenshot({ path: 'artifacts/workbench-git-tree-desktop.png', animations: 'disabled' });
  const splitTab = page.locator('.editor-group.active .editor-tab.diff-tab.active');
  await splitTab.click({ button: 'middle' });
  await page.waitForFunction(() => document.querySelectorAll('.editor-group').length === 1);
  assert(await page.locator('.editor-tab.diff-tab').count() === 2, 'Middle-click closes the split copy and restores the remaining pane');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#mobile-files-toggle').click();
  await page.locator('#files-sidebar.mobile-open').waitFor();
  await page.locator('#right-git-tab').click();
  await page.locator('[data-change-path="git-untracked.txt"][role="treeitem"]').click();
  await page.waitForFunction(() => document.querySelector('.git-diff-tab-path')?.textContent === 'git-untracked.txt');
  assert(!await page.locator('#files-sidebar').evaluate(node => node.classList.contains('mobile-open')), 'Selecting a tree file closes the mobile drawer and reveals its diff tab');
  await page.waitForFunction(() => [...document.querySelectorAll('.git-diff-tab .view-lines')].some(node => node.textContent.includes('untracked')));
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'The mobile diff tab fits without horizontal overflow');
  await page.screenshot({ path: 'artifacts/workbench-git-tree-mobile.png', animations: 'disabled' });
  await page.locator('#mobile-files-toggle').click();
  await page.getByRole('button', { name: 'Unbind', exact: true }).click();
  await page.locator('.git-repository-search').waitFor();
  await page.locator('.right-sidebar-close').click();
  await page.waitForFunction(() => !document.querySelector('.git-diff-tab .view-lines'));
  assert(await page.locator('.git-diff-tab-status').textContent().then(text => text.includes('no longer') || text.includes('associated')), 'Unbind clears stale content from an existing diff tab');
  assert(errors.length === 0, 'No tree/diff-tab runtime errors');
  return { checks, count: checks.length, errors };
}
