async page => {
  const base = 'http://127.0.0.1:17690';
  const checks = [], errors = [];
  const assert = (ok, message) => { if (!ok) throw new Error(message); checks.push(message); };
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto(base);
  await page.evaluate(async () => { for (const worker of await navigator.serviceWorker.getRegistrations()) await worker.unregister(); localStorage.clear(); });
  await page.reload();
  const alpha = page.locator('.session-card').filter({ hasText: 'workbench-alpha' });
  const beta = page.locator('.session-card').filter({ hasText: 'workbench-beta' });
  await alpha.click();
  await page.locator('.file-tree-row[data-path="README.md"]').waitFor();
  const initialTabs = await page.locator('.editor-tab').count();
  const drop = async (selector, files) => {
    const transfer = await page.evaluateHandle(specs => {
      const data = new DataTransfer();
      for (const spec of specs) data.items.add(new File([new Uint8Array(spec.bytes || Array.from(new TextEncoder().encode(spec.text)))], spec.name, { type: spec.type || 'application/octet-stream' }));
      return data;
    }, files);
    try { await page.locator(selector).dispatchEvent('dragenter', { dataTransfer: transfer }); await page.locator(selector).dispatchEvent('dragover', { dataTransfer: transfer }); await page.locator(selector).dispatchEvent('drop', { dataTransfer: transfer }); }
    finally { await transfer.dispose(); }
  };
  const readFile = async path => (await (await page.request.get(base + '/api/file?session=workbench-alpha&path=' + encodeURIComponent(path))).json());
  await drop('.file-browser-tree', [{ name: 'upload-root.txt', text: 'UPLOADED_FROM_DROP\n' }, { name: 'upload-binary.bin', bytes: [0, 255, 7, 128] }]);
  await page.locator('.file-tree-row[data-path="upload-root.txt"]').waitFor();
  await page.locator('.file-tree-row[data-path="upload-binary.bin"]').waitFor();
  assert((await readFile('upload-root.txt')).content === 'UPLOADED_FROM_DROP\n', 'Dropping files into sidebar uploads to the session root and refreshes its tree');
  assert(await page.locator('.editor-tab').count() === initialTabs, 'Upload does not create extra workspace tabs');
  await page.locator('.file-tree-row[data-path="src"]').click();
  await page.locator('.file-tree-row[data-path="src/main.js"]').waitFor();
  await drop('.file-tree-row[data-path="src"]', [{ name: 'nested.txt', text: 'NESTED_FOLDER_UPLOAD\n' }]);
  await page.locator('.file-tree-row[data-path="src/nested.txt"]').waitFor();
  assert((await readFile('src/nested.txt')).content.includes('NESTED_FOLDER_UPLOAD'), 'Dropping onto a directory uploads into that exact folder and preserves expansion');
  await drop('.file-tree-row[data-path="src/main.js"]', [{ name: 'sibling.txt', text: 'FILE_PARENT_UPLOAD\n' }]);
  await page.locator('.file-tree-row[data-path="src/sibling.txt"]').waitFor();
  assert((await readFile('src/sibling.txt')).content.includes('FILE_PARENT_UPLOAD'), 'Dropping onto a file uploads into its parent folder');
  await drop('.file-browser-tree', [{ name: 'upload-root.txt', text: 'MUST_NOT_OVERWRITE\n' }, { name: 'after-conflict.txt', text: 'AFTER_CONFLICT\n' }]);
  await page.locator('.file-tree-row[data-path="after-conflict.txt"]').waitFor();
  assert((await readFile('upload-root.txt')).content === 'UPLOADED_FROM_DROP\n', 'A duplicate filename preserves the original while the remaining batch uploads');
  await drop('.file-browser-tree', [{ name: 'upload-image.png', type: 'image/png', bytes: [137, 80, 78, 71, 13, 10, 26, 10, 0, 0, 0, 13, 73, 72, 68, 82, 0, 0, 0, 1, 0, 0, 0, 1, 8, 4, 0, 0, 0, 181, 28, 12, 2, 0, 0, 0, 11, 73, 68, 65, 84, 120, 218, 99, 252, 255, 31, 0, 3, 3, 2, 0, 239, 154, 15, 84, 0, 0, 0, 0, 73, 69, 78, 68, 174, 66, 96, 130] }]);
  await page.locator('.file-tree-row[data-path="upload-image.png"]').waitFor();
  await page.locator('.file-tree-row[data-path="upload-image.png"]').click();
  await page.waitForFunction(() => document.querySelector('.file-image-preview')?.naturalWidth === 1);
  assert(true, 'A real image dropped from a DataTransfer opens in an existing image tab');
  const internal = await page.evaluateHandle(() => { const data = new DataTransfer(); data.setData('text/plain', 'workbench-session'); return data; });
  await page.locator('.file-browser-tree').dispatchEvent('dragover', { dataTransfer: internal });
  assert(!await page.locator('.file-browser').evaluate(node => node.classList.contains('upload-drag-over')), 'Internal session and tab text drags do not activate file upload');
  await internal.dispose();
  await page.locator('#right-git-tab').click();
  await drop('#files-sidebar', [{ name: 'from-git.txt', text: 'GIT_SIDEBAR_UPLOAD\n' }]);
  await page.locator('.file-tree-row[data-path="from-git.txt"]').waitFor();
  assert(await page.locator('#files-content').isVisible() && (await readFile('from-git.txt')).content.includes('GIT_SIDEBAR_UPLOAD'), 'External drops on the Git sidebar reveal Files and use the session directory');
  let release, started;
  const waitStarted = () => new Promise(resolve => { started = resolve; });
  const blockedRequests = [];
  const handler = async route => {
    blockedRequests.push(route.request().url());
    started();
    await new Promise(resolve => { release = resolve; });
    await route.abort().catch(() => {});
  };
  await page.route('**/api/file/upload?*', handler);
  let pending = waitStarted();
  await drop('.file-browser-tree', [{ name: 'cancelled-refresh.txt', text: 'DO_NOT_PUBLISH' }]);
  await pending;
  await page.getByRole('button', { name: 'Refresh files', exact: true }).click();
  assert(await page.locator('.file-browser-refresh').isEnabled() && (await page.locator('.file-upload-status').textContent()).includes('cancelled'), 'Refreshing during upload cancels it and reports cancellation');
  release();
  await page.unroute('**/api/file/upload?*', handler);
  await page.route('**/api/file/upload?*', handler);
  pending = waitStarted();
  await drop('.file-browser-tree', [{ name: 'cancelled-switch.txt', text: 'DO_NOT_PUBLISH' }, { name: 'queued-switch.txt', text: 'DO_NOT_QUEUE' }]);
  await pending;
  await beta.click();
  release();
  await page.unroute('**/api/file/upload?*', handler);
  assert(blockedRequests.length === 2 && await page.locator('.file-browser-refresh').isEnabled(), 'Session switching aborts the active upload and cancels its remaining queue');
  await page.waitForFunction(async () => {
    const session = (await (await fetch('/api/sessions')).json()).sessions.find(item => item.name === 'workbench-beta');
    if (!session) return false;
    return (await (await fetch('/api/files?' + new URLSearchParams({ session: session.id }))).json()).root === '/tmp/workbench-e2e/other';
  });
  await drop('.file-browser-tree', [{ name: 'beta.txt', text: 'BETA_ONLY_UPLOAD\n' }]);
  await page.locator('.file-tree-row[data-path="beta.txt"]').waitFor();
  const alphaMissing = await page.request.get(base + '/api/file?session=workbench-alpha&path=beta.txt');
  assert(alphaMissing.status() === 404, 'Upload destination follows the selected session without leaking into another session');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#mobile-files-toggle').click();
  await page.locator('#files-sidebar.mobile-open').waitFor();
  await drop('.file-browser-tree', [{ name: 'phone.txt', text: 'PHONE_DROP_UPLOAD\n' }]);
  await page.locator('.file-tree-row[data-path="phone.txt"]').waitFor();
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Phone file drop uploads without horizontal overflow');
  await page.screenshot({ path: 'artifacts/workbench-upload-mobile.png', animations: 'disabled' });
  await page.setViewportSize({ width: 1440, height: 900 });
  await alpha.click();
  await page.screenshot({ path: 'artifacts/workbench-upload-desktop.png', animations: 'disabled' });
  assert(errors.length === 0, 'No file upload browser runtime errors');
  return { checks, count: checks.length, errors };
}
