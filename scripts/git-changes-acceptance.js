async page => {
  const base = 'http://127.0.0.1:17690';
  const repo = '/tmp/workbench-e2e/project/repos/other';
  const checks = [], errors = [];
  const assert = (ok, message) => { if (!ok) throw new Error(message); checks.push(message); };
  page.on('pageerror', error => errors.push(error.message));
  const sessions = (await (await page.request.get(base + '/api/sessions')).json()).sessions;
  const alpha = sessions.find(session => session.name === 'workbench-alpha');
  if (!alpha) throw new Error('Missing owned fixture');
  const status = async () => (await (await page.request.get(base + '/api/git?session=' + encodeURIComponent(alpha.id))).json());
  let current = await status();
  if (current.association.path) await page.request.put(base + '/api/git/association', { headers: { Origin: base }, data: { session: alpha.id, path: null, revision: current.association.revision } });
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto(base);
  await page.evaluate(async () => { for (const worker of await navigator.serviceWorker.getRegistrations()) await worker.unregister(); localStorage.clear(); });
  await page.reload();
  await page.locator('.session-card').filter({ hasText: alpha.name }).click();
  await page.locator('#right-git-tab').click();
  await page.locator(`.git-recommendation[data-repository-path="${repo}"]`).click();
  await page.locator('.git-diff-editor .monaco-diff-editor').waitFor();
  const tabs = await page.locator('.editor-tab').count();
  const headings = await page.locator('.git-change-group-heading').allTextContents();
  assert(headings.some(text => text.startsWith('Staged')) && headings.some(text => text.startsWith('Changes')) && headings.some(text => text.startsWith('Untracked')), 'Changes are grouped by index, working tree, and untracked files');
  const rowHeight = await page.locator('.git-change-variant').first().evaluate(node => node.getBoundingClientRect().height);
  assert(rowHeight <= 36, 'Changed files use compact clickable rows');
  const filter = page.getByRole('searchbox', { name: 'Filter changed files' });
  await filter.fill('BOTH');
  assert(await page.locator('.git-change-variant').count() === 2, 'Filename filtering retains both index and working-tree variants');
  await page.locator('.git-change-variant[data-change-kind="staged"]').click();
  await page.waitForFunction(() => document.querySelector('.git-diff-kind')?.textContent === 'staged');
  await page.getByRole('button', { name: 'Next changed file', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.git-diff-kind')?.textContent === 'unstaged');
  assert(await page.locator('.git-diff-position').textContent() === '2 / 2', 'Next file traverses the filtered variants and shows position');
  await page.getByRole('button', { name: 'Previous changed file', exact: true }).click();
  assert(await page.locator('.git-diff-kind').textContent() === 'staged', 'Previous file returns to the index version');
  await filter.fill('rename OLD');
  assert(await page.locator('.git-change-variant').count() === 2, 'Filtering matches renamed old paths and multiple keywords');
  await filter.fill('no such path');
  assert(await page.locator('.git-changes-list').textContent().then(text => text.includes('No changed files')), 'Empty filter results are explained');
  assert(await page.locator('.git-diff-kind').textContent() === 'staged', 'Filtering keeps the current diff visible');
  await filter.fill('');
  await page.getByRole('button', { name: 'Expand diff', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Review Git changes' });
  await dialog.waitFor();
  await page.waitForFunction(() => document.querySelector('.git-review-dialog .git-diff-editor')?.getBoundingClientRect().height > 500);
  await page.waitForFunction(() => document.querySelector('.git-review-dialog .monaco-diff-editor')?.getBoundingClientRect().height > 500);
  const bounds = await dialog.locator('.git-diff-editor').boundingBox();
  assert(bounds.width > 900 && bounds.height > 500, 'Expanded review gives desktop diff most of the screen');
  assert(await dialog.locator('.git-changes-filter').isVisible() && await dialog.locator('.git-change-variant').count() > 5, 'Expanded review keeps file filtering and switching beside the diff');
  await dialog.locator('[data-change-path="git-untracked.txt"]').click();
  await page.waitForFunction(() => document.querySelector('.git-review-dialog .git-diff-title')?.textContent === 'git-untracked.txt');
  await page.waitForFunction(() => [...document.querySelectorAll('.git-review-dialog .view-lines')].some(node => node.textContent.replace(/\u00a0/g, ' ').includes('untracked content visible')));
  await page.screenshot({ path: 'artifacts/workbench-git-changes-desktop.png', animations: 'disabled' });
  assert(await page.locator('.editor-tab').count() === tabs, 'Expanded review creates no workspace tabs');
  await page.keyboard.press('Escape');
  await dialog.waitFor({ state: 'hidden' });
  assert(await page.locator('.git-panel .git-diff-title').textContent() === 'git-untracked.txt', 'Escape returns the same selected diff to the sidebar');
  assert(await page.getByRole('button', { name: 'Expand diff', exact: true }).evaluate(node => node === document.activeElement), 'Closing review restores focus to its trigger');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#mobile-files-toggle').click();
  await page.locator('#files-sidebar.mobile-open').waitFor();
  await page.getByRole('button', { name: 'Expand diff', exact: true }).click();
  await dialog.waitFor();
  await page.waitForFunction(() => document.querySelector('.git-review-dialog .git-diff-editor')?.getBoundingClientRect().height > 400);
  await page.waitForFunction(() => document.querySelector('.git-review-dialog .monaco-diff-editor')?.getBoundingClientRect().height > 400);
  assert(await page.evaluate(() => document.documentElement.scrollWidth === innerWidth), 'Mobile expanded review fits the viewport');
  await dialog.locator('.git-changes-filter').fill('untracked');
  await dialog.locator('[data-change-path="git-untracked.txt"]').click();
  await page.waitForFunction(() => [...document.querySelectorAll('.git-review-dialog .view-lines')].some(node => node.textContent.replace(/\u00a0/g, ' ').includes('untracked content visible')));
  await page.screenshot({ path: 'artifacts/workbench-git-changes-mobile.png', animations: 'disabled' });
  await page.keyboard.press('Tab');
  assert(await dialog.evaluate(node => node.contains(document.activeElement)), 'Mobile keyboard focus stays inside expanded review');
  await page.keyboard.press('Escape');
  await dialog.waitFor({ state: 'hidden' });
  assert(await page.locator('#files-sidebar.mobile-open').isVisible() && await page.locator('.git-panel .git-changes-filter').inputValue() === 'untracked', 'Closing mobile review preserves the drawer and file filter');
  await page.locator('.git-panel .git-changes-filter').fill('');
  await page.getByRole('button', { name: 'Expand diff', exact: true }).click();
  current = await status();
  await page.request.put(base + '/api/git/association', { headers: { Origin: base }, data: { session: alpha.id, path: null, revision: current.association.revision } });
  await page.evaluate(() => document.querySelector('.git-refresh').click());
  await dialog.waitFor({ state: 'hidden' });
  await page.locator('.git-repository-search').waitFor();
  assert(!await page.locator('.git-diff-section').isVisible(), 'Remote Unbind closes review and clears stale diff content');
  assert(errors.length === 0, 'No Changes browser runtime errors');
  return { checks, count: checks.length, errors, rowHeight, desktopDiff: bounds };
}
