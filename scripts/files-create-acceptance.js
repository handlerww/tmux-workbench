async page => {
  const base = 'http://127.0.0.1:17690', checks = [], errors = [];
  const assert = (ok, message) => { if (!ok) throw new Error(message); checks.push(message); };
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto(base);
  await page.evaluate(async () => { for (const worker of await navigator.serviceWorker.getRegistrations()) await worker.unregister(); localStorage.clear(); });
  await page.reload();
  const sessions = (await (await page.request.get(base + '/api/sessions')).json()).sessions;
  const alpha = sessions.find(s => s.name === 'workbench-alpha');
  const read = async path => await (await page.request.get(base + '/api/file?session=' + encodeURIComponent(alpha.id) + '&path=' + encodeURIComponent(path))).json();
  const row = path => page.locator('.file-tree-row[data-path="' + path + '"]');
  const input = page.locator('.file-create-input');
  await page.locator('.session-card').filter({ hasText: alpha.name }).click();
  await row('README.md').waitFor();
  assert(await page.locator('.file-browser-root, .file-browser-upload-target, .file-browser-upload, .file-upload-input').count() === 0, 'Files omits directory/Upload-to rows and the upload picker button');
  assert(await page.getByRole('button', { name: 'New file', exact: true }).isEnabled() && await page.getByRole('button', { name: 'New folder', exact: true }).isEnabled(), 'New file/folder glyph actions are available beside Refresh');
  await page.getByRole('button', { name: 'New file', exact: true }).click();
  assert(await input.evaluate(n => document.activeElement === n), 'New file focuses an inline tree draft');
  await input.press('Escape');
  assert(await input.count() === 0 && await page.getByRole('button', { name: 'New file', exact: true }).evaluate(n => document.activeElement === n), 'Escape cancels the draft and restores toolbar focus');
  await page.getByRole('button', { name: 'New folder', exact: true }).click();
  await input.press('Tab');
  assert(await input.count() === 0, 'Leaving the name field cancels an unsubmitted draft');
  await page.getByRole('button', { name: 'New file', exact: true }).click();
  await input.press('Enter');
  assert(await page.locator('.file-create-feedback').textContent() === 'Enter a file name.', 'Empty names stay editable with inline validation');
  await input.fill('toolbar-created.txt');
  await input.dispatchEvent('compositionstart');
  await input.dispatchEvent('keydown', { key: 'Enter', code: 'Enter', isComposing: true });
  await page.locator('.file-create-row').dispatchEvent('submit');
  assert((await page.request.get(base + '/api/file?session=' + encodeURIComponent(alpha.id) + '&path=toolbar-created.txt')).status() === 404, 'IME Enter and submit during composition do not create a file');
  await input.dispatchEvent('compositionend');
  await input.press('Enter');
  await row('toolbar-created.txt').waitFor();
  await page.locator('.file-editor-panel .monaco-editor').waitFor();
  assert((await read('toolbar-created.txt')).content === '', 'Enter creates an actual empty file');
  assert(await page.locator('.editor-tab.file-tab.active [aria-label="Unpin file tab"]').count() === 1, 'The new file opens as a pinned workspace tab');
  await page.locator('.file-editor-panel .monaco-editor').click();
  await page.keyboard.press('Control+End');
  await page.keyboard.insertText('NEW_FILE_SAVED\n');
  await page.locator('.file-editor-panel .file-editor-dirty').waitFor({ state: 'visible' });
  await page.keyboard.press('Control+s');
  await page.locator('.file-editor-panel .file-editor-dirty').waitFor({ state: 'hidden' });
  assert((await read('toolbar-created.txt')).content === 'NEW_FILE_SAVED\n', 'A newly created file is editable and Ctrl-S saves real content');
  const original = (await read('README.md')).content;
  await page.getByRole('button', { name: 'New file', exact: true }).click();
  await input.fill('README.md'); await input.press('Enter');
  await page.locator('.file-create-feedback.is-error').waitFor();
  assert((await read('README.md')).content === original && await input.inputValue() === 'README.md', 'Duplicate names preserve existing bytes and the editable draft');
  await input.fill('../escape-created.txt'); await input.press('Enter');
  await page.waitForFunction(() => document.querySelector('.file-create-feedback.is-error')?.textContent.includes('relative'));
  assert(await input.count() === 1, 'Traversal is rejected without discarding the draft');
  await input.press('Escape');
  await page.getByRole('button', { name: 'New folder', exact: true }).click();
  await input.fill('toolbar-created'); await input.press('Enter');
  await row('toolbar-created').waitFor();
  assert(await row('toolbar-created').getAttribute('aria-expanded') === 'true', 'New folders are created and expanded in the tree');
  await page.getByRole('button', { name: 'New file', exact: true }).click();
  await input.fill('toolbar-created/child.txt'); await input.press('Enter');
  await row('toolbar-created/child.txt').waitFor();
  assert((await read('toolbar-created/child.txt')).content === '', 'Relative paths can create a file in an existing subfolder');
  await page.getByRole('button', { name: 'New folder', exact: true }).click();
  await input.fill('cancelled-folder');
  await page.getByRole('button', { name: 'Refresh files', exact: true }).click();
  assert(await input.count() === 0, 'Refresh clears an unsubmitted creation draft');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#mobile-files-toggle').click();
  await page.getByRole('button', { name: 'New folder', exact: true }).click();
  assert(await input.evaluate(n => parseFloat(getComputedStyle(n).fontSize) >= 16), 'Phone name input uses readable text without automatic zoom');
  assert(await page.getByRole('button', { name: 'New folder', exact: true }).evaluate(n => n.getBoundingClientRect().height >= 36), 'Phone creation controls have larger touch targets');
  await input.fill('toolbar-phone'); await input.press('Enter'); await row('toolbar-phone').waitFor();
  assert(await page.locator('#files-sidebar').evaluate(n => n.classList.contains('mobile-open')), 'Creating a phone folder keeps the Files drawer available');
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Phone toolbar and creation draft have no horizontal overflow');
  await page.screenshot({ path: 'artifacts/files-toolbar-mobile.png', animations: 'disabled' });
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.screenshot({ path: 'artifacts/files-toolbar-desktop.png', animations: 'disabled' });
  await page.getByRole('button', { name: 'New file', exact: true }).click(); await input.fill('cancelled-switch.txt');
  await page.locator('.session-card').filter({ hasText: 'workbench-beta' }).click();
  await row('README.md').waitFor();
  assert(await input.count() === 0, 'Switching sessions clears the old creation draft');
  assert(errors.length === 0, 'No creation, editor or toolbar runtime errors');
  return { checks, count: checks.length, errors };
}
