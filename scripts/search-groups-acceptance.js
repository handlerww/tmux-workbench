async page => {
  const base = 'http://127.0.0.1:17690';
  const checks = [];
  const errors = [];
  const assert = (value, label) => { if (!value) throw new Error(label); checks.push(label); };
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto(base);
  await page.evaluate(async () => {
    for (const registration of await navigator.serviceWorker.getRegistrations()) await registration.unregister();
    for (const key of await caches.keys()) if (key.startsWith('workbench-shell-')) await caches.delete(key);
    localStorage.clear();
  });
  const state = await (await page.request.get(base + '/api/groups')).json();
  const reset = await page.request.put(base + '/api/groups', { headers: { Origin: base }, data: { groups: [], assignments: {}, ungroupedCollapsed: false, revision: state.revision } });
  if (!reset.ok()) throw new Error('Cannot reset isolated groups fixture');
  await page.reload();
  await page.locator('.session-card').first().waitFor();
  const sessions = (await (await page.request.get(base + '/api/sessions')).json()).sessions;
  const alpha = sessions.find(session => session.name === 'workbench-alpha').id;
  const beta = sessions.find(session => session.name === 'workbench-beta').id;
  const snapshot = async () => (await page.request.get(base + '/api/groups')).json();
  await page.locator('#session-search-input').fill('workbench-alpha');
  await page.evaluate(() => { window.prompt = () => 'Existing group'; });
  await page.getByRole('button', { name: 'Create group from 1 Untagged result', exact: true }).click();
  await page.waitForFunction(async () => (await (await fetch('/api/groups')).json()).groups.some(group => group.name === 'Existing group'));
  const existing = (await snapshot()).groups.find(group => group.name === 'Existing group');
  await page.locator('#session-search-input').fill('workbench-');
  assert(await page.locator('.session-card').count() === 2, 'Search shows matching tagged and Untagged sessions');
  assert(await page.locator('.search-group-summary').textContent() === '2 matches · 1 Untagged', 'Search reports total matches and eligible Untagged count separately');
  await page.evaluate(() => { window.prompt = () => 'New group'; });
  await page.getByRole('button', { name: 'Create group from 1 Untagged result', exact: true }).click();
  await page.waitForFunction(async () => (await (await fetch('/api/groups')).json()).groups.some(group => group.name === 'New group'));
  const created = (await snapshot()).groups.find(group => group.name === 'New group');
  const assigned = (await snapshot()).assignments;
  assert(assigned[alpha] === existing.id && assigned[beta] === created.id, 'Search group creation keeps existing membership and assigns only Untagged matches');
  assert(await page.locator('#session-search-input').inputValue() === '', 'Creating a group still clears the search');
  await page.getByRole('button', { name: 'Manage Existing group', exact: true }).click();
  assert(await page.getByRole('menuitem', { name: 'Rename group', exact: true }).isVisible() && await page.getByRole('menuitem', { name: 'Dissolve group', exact: true }).isVisible(), 'Group menu exposes explicit rename and dissolve actions');
  await page.evaluate(() => { window.prompt = () => 'Renamed group'; });
  await page.getByRole('menuitem', { name: 'Rename group', exact: true }).click();
  await page.waitForFunction(async id => (await (await fetch('/api/groups')).json()).groups.find(group => group.id === id)?.name === 'Renamed group', existing.id);
  assert((await snapshot()).assignments[alpha] === existing.id, 'Renaming a group preserves its ID and session membership on the server');
  await page.locator('#session-search-input').fill('workbench-');
  assert(await page.locator('.search-group-action').count() === 0 && await page.locator('.session-card').count() === 2, 'All-tagged search keeps displaying results and hides group creation');
  assert(await page.locator('.session-card-row select').count() === 0, 'Session cards have no group dropdowns');
  await page.locator('.session-card').filter({ hasText: 'workbench-alpha' }).dragTo(page.locator(`.workspace-section[data-session-group-id="${created.id}"] .workspace-section-heading`));
  await page.waitForFunction(async ({ id, group }) => (await (await fetch('/api/groups')).json()).assignments[id] === group, { id: alpha, group: created.id });
  assert(true, 'A tagged search result can move to another existing group');
  await page.locator('#session-search-input').fill('');
  await page.locator('.session-card').filter({ hasText: 'workbench-beta' }).dragTo(page.locator('.workspace-section[data-session-group-id=""] .workspace-section-heading'));
  await page.locator('#session-search-input').fill('workbench-');
  await page.waitForFunction(async id => !(await (await fetch('/api/groups')).json()).assignments[id], beta);
  assert(await page.getByRole('button', { name: 'Create group from 1 Untagged result', exact: true }).isEnabled(), 'Moving a result to Untagged makes it eligible for group creation');
  await page.getByRole('combobox', { name: 'Move search results to a group', exact: true }).selectOption(created.id);
  await page.waitForFunction(async ({ a, b, group }) => { const state = await (await fetch('/api/groups')).json(); return state.assignments[a] === group && state.assignments[b] === group; }, { a: alpha, b: beta, group: created.id });
  assert(await page.locator('.session-card').count() === 2 && await page.locator('#session-search-input').inputValue() === 'workbench-', 'Explicit bulk move changes all matches while retaining the search results');
  await page.reload();
  await page.locator('.session-card').first().waitFor();
  assert((await snapshot()).groups.find(group => group.id === existing.id)?.name === 'Renamed group', 'Group rename remains persisted when its empty group is hidden by search');
  assert(await page.locator(`.workspace-section[data-session-group-id="${created.id}"] .session-card`).count() === 2, 'Renamed groups and changed assignments survive reload');
  await page.getByRole('combobox', { name: 'Move search results to a group', exact: true }).selectOption('');
  await page.waitForFunction(async () => Object.keys((await (await fetch('/api/groups')).json()).assignments).length === 0);
  assert(await page.getByRole('button', { name: 'Create group from 2 Untagged results', exact: true }).isEnabled(), 'Bulk move back to Untagged restores eligibility for all matching sessions');
  assert(errors.length === 0, 'No search-group browser runtime errors');
  await page.screenshot({ path: 'artifacts/workbench-search-groups.png', animations: 'disabled' });
  return { checks, count: checks.length, errors };
}
