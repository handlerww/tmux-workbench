async page => {
  await page.setViewportSize({ width: 1440, height: 900 });
  const base = 'http://127.0.0.1:17690';
  const repo = '/tmp/workbench-e2e/project/repos/other';
  const checks = [], errors = [];
  let searchRequests = 0;
  const assert = (ok, message) => { if (!ok) throw new Error(message); checks.push(message); };
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (request.url().includes('/api/git/recommendations?')) searchRequests++; });
  const sessions = (await (await page.request.get(base + '/api/sessions')).json()).sessions;
  const fixture = sessions.find(session => session.name === 'workbench-git-cwd');
  if (!fixture) throw new Error('Missing owned git-cwd fixture');
  const status = async () => (await (await page.request.get(base + '/api/git?session=' + encodeURIComponent(fixture.id))).json());
  const initial = await status();
  assert(fixture.path === repo && initial.repository === null && initial.association.path === null,
    'A session directly in a Git repository remains unbound');
  await page.goto(base);
  await page.evaluate(async () => {
    for (const worker of await navigator.serviceWorker.getRegistrations()) await worker.unregister();
    localStorage.clear();
  });
  await page.reload();
  await page.locator('.session-card').filter({ hasText: fixture.name }).click();
  await page.locator('#right-git-tab').click();
  const input = page.locator('.git-repository-search');
  const candidate = page.locator(`.git-recommendation[data-repository-path="${repo}"]`);
  await candidate.waitFor();
  assert(await input.isVisible() && !await page.locator('.git-repository-card').isVisible(),
    'Unbound Git cwd shows candidates instead of repository state');
  assert((await status()).association.path === null, 'Discovery does not persist an association');
  assert(await candidate.textContent().then(text => text.includes('Current directory')), 'Current directory is offered as a candidate');
  await input.fill('OTHER');
  await candidate.waitFor();
  await candidate.click();
  await page.locator('.git-repository-picker').waitFor({ state: 'hidden' });
  await page.locator('.git-change-row').first().waitFor();
  await page.locator('.git-change-variant').first().click();
  await page.locator('.git-diff-tab-editor .original-in-monaco-diff-editor').waitFor();
  assert((await status()).association.path === repo, 'Only choosing a candidate writes the association');
  assert(!await input.isVisible() && !await page.locator('.git-recommendations').isVisible(), 'Binding hides both search and recommendations');
  assert(await page.getByRole('button', { name: 'Unbind', exact: true }).isVisible(), 'Bound state provides Unbind');
  const boundRequests = searchRequests;
  await page.getByRole('button', { name: 'Refresh Git status' }).click();
  await page.locator('#right-files-tab').click();
  await page.locator('#right-git-tab').click();
  await page.waitForTimeout(400);
  assert(searchRequests === boundRequests, 'Refreshing and reopening a bound Git panel do not scan for recommendations');
  await page.reload();
  await page.locator('.session-card').filter({ hasText: fixture.name }).click();
  await page.locator('#right-git-tab').click();
  await page.getByRole('button', { name: 'Unbind', exact: true }).waitFor();
  assert(!await input.isVisible() && (await status()).association.path === repo, 'Reload restores the association without reopening the picker');
  await page.getByRole('button', { name: 'Unbind', exact: true }).click();
  await candidate.waitFor();
  const unbound = await status();
  assert(unbound.association.path === null && unbound.repository === null && !unbound.changes.length, 'Unbind clears status even when cwd is itself a repository');
  assert(!await page.locator('.git-pr-card').isVisible() && await page.locator('.git-diff-tab-editor .view-lines').count() === 0, 'Unbind removes PR and diff content');
  const diff = await page.request.get(base + '/api/git/diff?session=' + encodeURIComponent(fixture.id) + '&repository=' + encodeURIComponent(repo) + '&path=git-staged.txt&kind=staged');
  assert(diff.status() === 409, 'Diff requires an explicit association after Unbind');
  assert(await input.inputValue() === '', 'Unbind reopens a fresh candidate picker');
  await page.reload();
  await page.locator('.session-card').filter({ hasText: fixture.name }).click();
  await page.locator('#right-git-tab').click();
  await candidate.waitFor();
  assert((await status()).association.path === null, 'Reload does not automatically rebind the Git cwd');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#mobile-files-toggle').click();
  await page.locator('#files-sidebar.mobile-open').waitFor();
  await candidate.click();
  await page.getByRole('button', { name: 'Unbind', exact: true }).waitFor();
  assert(!await input.isVisible(), 'Mobile binding also hides the picker');
  await page.getByRole('button', { name: 'Unbind', exact: true }).click();
  await candidate.waitFor();
  assert(await input.isVisible() && await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile Unbind restores the picker without overflow');
  assert(errors.length === 0, 'No browser runtime errors');
  return { checks, count: checks.length, errors };
}
