    const touch = (x, type) => target.dispatchEvent(new TouchEvent(type, { bubbles: true, touches: type === 'touchstart' ? [new Touch({ identifier: 1, target, clientX: x, clientY: 300 })] : [], changedTouches: [new Touch({ identifier: 1, target, clientX: x, clientY: 300 })] }));
