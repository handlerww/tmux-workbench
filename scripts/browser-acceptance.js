  await page.locator('.file-editor-name').filter({ hasText: 'main.js' }).waitFor();
  await page.locator('.editor-tab.file-tab.active [aria-label="Unpin file tab"]').waitFor();
  assert(true, 'Double-click opens a pinned file tab');
  await page.locator('.file-tree-row[data-path="pixel.png"]').click();
  await page.waitForFunction(() => { const image = document.querySelector('.file-editor-panel:not([hidden]) .file-image-preview'); return image?.complete && image.naturalWidth === 1; });
  assert(await page.locator('.file-editor-panel:not([hidden]) .file-editor-image').isVisible(), 'PNG opens in an image preview tab');
  await page.locator('.file-tree-row[data-path="sample.svg"]').dblclick();
  await page.waitForFunction(() => { const image = document.querySelector('.file-editor-panel:not([hidden]) .file-image-preview'); return image?.complete && image.naturalWidth === 120; });
  await page.locator('.editor-tab.file-tab.active [aria-label="Unpin file tab"]').waitFor();
  assert(true, 'SVG opens as a pinned image tab');
  await page.locator('.file-editor-panel:not([hidden]) .file-image-mode[data-mode="actual"]').click();
  assert(await page.locator('.file-editor-panel:not([hidden]) .file-image-mode[data-mode="actual"]').getAttribute('aria-pressed') === 'true', 'Image tabs support actual size and fit modes');
  await page.screenshot({ animations: 'disabled', path: 'artifacts/workbench-image.png' });
  await page.getByRole('button', { name: 'Close workbench-alpha', exact: true }).click();
  await page.locator('.session-card').filter({ hasText: 'workbench-alpha' }).click();
  await page.getByRole('button', { name: 'Close workbench-alpha', exact: true }).waitFor();
  assert(await page.locator('.editor-panel').count() === 1, 'Session can reopen its terminal when only file tabs remain');
  await page.locator('.reader-input').fill('printf "WORKBENCH_ACCEPTANCE_OK\\n"');
  await page.locator('.reader-input').press('Enter');
  await page.waitForFunction(() => document.querySelector('.reader-content')?.textContent.includes('WORKBENCH_ACCEPTANCE_OK'), { timeout: 10000 });
  assert(true, 'Reader sends input to a real isolated tmux session');
  await page.getByRole('button', { name: 'Terminal', exact: true }).click();
  await page.locator('.terminal-shell:not([hidden])').waitFor();
  assert(!(await page.evaluate(() => document.activeElement?.matches('textarea,input'))), 'Terminal mode switch does not autofocus input');
  await page.getByRole('button', { name: 'Reader', exact: true }).click();
  await page.locator('.session-card').filter({ hasText: 'workbench-beta' }).click();
  const betaSession = await sessionByName('workbench-beta');
  await waitForFileRoot(betaSession.id, '/tmp/workbench-e2e/other');
  assert(await page.locator('.file-tree-row[data-path="config.json"]').count() === 0, 'Switching sessions clears the previous file tree');
