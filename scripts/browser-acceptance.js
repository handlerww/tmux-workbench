  const listing = await directory.json();
  const preview = await page.request.get('http://127.0.0.1:17690/api/file?session=workbench-alpha&path=README.md');
  assert(directory.ok() && (await preview.json()).content.includes('Workbench browser fixture') && listing.root.endsWith('/project'), 'Real file list and preview APIs work');
