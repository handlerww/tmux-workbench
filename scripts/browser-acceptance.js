    const previewWasVisible = getComputedStyle(overlay).display !== 'none';
    source.remove();
    source.dispatchEvent(new DragEvent('dragend', { bubbles: true, dataTransfer: transfer }));
    await new Promise(resolve => requestAnimationFrame(resolve));
    return previewWasVisible && !document.body.classList.contains('workspace-item-dragging') && [...document.querySelectorAll('.editor-drop-overlay')].every(item => getComputedStyle(item).display === 'none') && !document.querySelector('.session-card.dragging');
