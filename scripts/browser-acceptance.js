  await page.locator('.file-editor-panel:not([hidden]) .monaco-editor').waitFor();
  await page.waitForFunction(() => document.querySelector('.file-editor-panel:not([hidden]) .view-lines')?.textContent.replace(/\u00a0/g, ' ').includes('Workbench browser fixture'));
  assert(true, 'Monaco loads the real file content');
  await page.locator('.file-tree-row[data-path="config.json"]').click();
  await page.locator('.file-editor-name').filter({ hasText: 'config.json' }).waitFor();
  assert(await page.locator('.editor-tab.file-tab').count() === 1, 'Single-click previews replace the existing preview tab');
  await page.getByRole('button', { name: 'Pin file tab', exact: true }).click();
  await page.locator('.file-tree-row[data-path="README.md"]').click();
  await page.locator('.file-editor-name').filter({ hasText: 'README.md' }).waitFor();
  assert(await page.locator('.editor-tab.file-tab').count() === 2, 'Pinned file stays open when another file is previewed');
  await page.locator('.file-tree-row[data-path="src"]').click();
  await page.locator('.file-tree-row[data-path="src/main.js"]').waitFor();
  assert(await page.locator('.file-tree-row[data-path="src/main.js"]').count() === 1, 'Expanding a directory loads its children once');
