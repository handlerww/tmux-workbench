  assert(await page.locator('.workspace-section[data-session-group-id=""] .section-fold').getAttribute('aria-expanded') === 'false', 'Untagged folded state survives reload');
  await page.locator('#session-search-input').fill('workbench-beta');
  await page.locator('.session-card').filter({ hasText: 'workbench-beta' }).waitFor();
  assert(true, 'Search exposes matches inside a collapsed default group');
  await page.locator('#session-search-input').fill('');
  assert(await page.locator('.session-card').filter({ hasText: 'workbench-beta' }).count() === 0, 'Clearing search restores the saved collapsed state');
  await page.locator('.workspace-section[data-session-group-id=""] .section-fold').click();
  await page.locator('.session-card').filter({ hasText: 'workbench-beta' }).waitFor();
