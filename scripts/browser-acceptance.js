    const connected = window.fixtureDragSource.isConnected;
    window.fixtureDragSource.dispatchEvent(new DragEvent('dragend', { bubbles: true, dataTransfer: new DataTransfer() }));
    delete window.fixtureDragSource;
    return connected && !document.body.classList.contains('workspace-item-dragging');
