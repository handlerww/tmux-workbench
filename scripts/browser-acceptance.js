    const target = document.querySelector('.file-browser-tree');
    const touch = (x, type) => target.dispatchEvent(new TouchEvent(type, { bubbles: true, touches: type === 'touchstart' ? [new Touch({ identifier: 2, target, clientX: x, clientY: 300 })] : [], changedTouches: [new Touch({ identifier: 2, target, clientX: x, clientY: 300 })] }));
